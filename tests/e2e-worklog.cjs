// Work Log end-to-end checks (Playwright, Chromium)
const { chromium } = require('playwright')
const path = require('path')
const SHOTS = process.env.SHOTS || require('path').resolve(__dirname, '.out/shots') + '/'
require('fs').mkdirSync(SHOTS, { recursive: true })
const PAGE = process.env.PAGE || 'file://' + path.resolve(__dirname, '../dist/preview.html')
let pass = 0, fail = 0
const ok = (c, name) => { if (c) { pass++; console.log('  ✓', name) } else { fail++; console.log('  ✗', name) } }
const num = (s) => Number(String(s).replace(/[۰-۹]/g, (d) => '۰۱۲۳۴۵۶۷۸۹'.indexOf(d)).replace('٫', '.').replace(/[^0-9.]/g, ''))

;(async () => {
  const b = await chromium.launch()
  const errs = []
  const open = async (scheme = 'light', vp = { width: 1366, height: 900 }) => {
    const p = await b.newPage({ viewport: vp, colorScheme: scheme })
    p.on('pageerror', (e) => errs.push(e.message))
    await p.goto(PAGE); await p.waitForTimeout(300)
    return p
  }
  const login = async (p, u) => { await p.fill('#li-user', u); await p.fill('#li-pass', 'pargar1405'); await p.click('button[type=submit]'); await p.waitForTimeout(400) }
  const logged = async (p) => num(await p.locator('#worklog dt:text-is("Logged Time") + dd').innerText())

  console.log('مسئول تسک')
  let p = await open()
  await login(p, 's.rezaei')
  await p.locator('[role=tabpanel] tbody tr:not(:has-text("صادر شد"))').first().click(); await p.waitForTimeout(500)
  ok(await p.locator('#worklog').count(), 'بخش Work Log در صفحه‌ی تسک')
  for (const k of ['Original Estimation', 'Logged Time', 'Remaining Time', 'Time Progress']) ok(await p.locator(`#worklog dt:text-is("${k}")`).count(), `شاخص ${k}`)
  ok(await p.locator('#worklog >> text=سوابق شما').count(), 'عضو فقط «سوابق شما» را می‌بیند')
  const taskTitle = (await p.locator('#task-drawer-scroll h2').first().innerText()).trim()
  const before = await logged(p)
  await p.fill('#wl-h', '2'); await p.locator('#wl-m').click(); await p.getByRole('option', { name: '۳۰' }).click()
  await p.fill('#wl-desc', 'آزمون E2E: اصلاح اندازه‌گذاری')
  await p.getByRole('button', { name: 'ثبت زمان' }).click(); await p.waitForTimeout(250)
  const after = await logged(p)
  ok(Math.abs(after - before - 2.5) < 0.06, `Logged Time بلافاصله ۲٫۵ ساعت بیشتر شد (${before} ← ${after})`)
  ok(await p.locator('#worklog >> text=آزمون E2E: اصلاح اندازه‌گذاری').count(), 'رکورد تازه در سوابق آمد')
  await p.locator('#worklog').scrollIntoViewIfNeeded()
  await p.screenshot({ path: SHOTS + 'wl-member.png' })
  // edit own record
  const row = p.locator('#worklog li:has-text("آزمون E2E: اصلاح اندازه‌گذاری")')
  await row.getByLabel('ویرایش رکورد').click(); await p.waitForTimeout(100)
  await p.locator('#worklog li input[aria-label="ساعت"]').fill('3'); await p.locator('#worklog li input[aria-label="دقیقه"]').fill('0')
  await p.locator('#worklog li').getByRole('button', { name: 'ذخیره' }).click(); await p.waitForTimeout(250)
  ok(Math.abs((await logged(p)) - before - 3) < 0.06, 'بعد از ویرایش، جمع به‌روز شد')
  await p.locator('#worklog li:has-text("آزمون E2E")').getByRole('button', { name: /ویرایش‌شده/ }).click(); await p.waitForTimeout(100)
  ok(await p.locator('#worklog >> text=قبلاً: ۲ ساعت و ۳۰ دقیقه').count(), 'مقدار قبلی در تاریخچه‌ی رکورد دیده می‌شود')
  // validation: future date is not offered as valid
  await p.fill('#wl-h', '30'); await p.fill('#wl-desc', 'بیش از حد'); await p.getByRole('button', { name: 'ثبت زمان' }).click(); await p.waitForTimeout(200)
  ok((await p.locator('[data-sonner-toast]').allInnerTexts()).join(' ').includes('۲۴ ساعت') || (await logged(p)) - before < 3.1, 'ثبت بیش از ۲۴ ساعت در یک روز پذیرفته نشد')
  await p.keyboard.press('Escape')

  console.log('کنترل پروژه (همان جلسه‌ی مرورگر)')
  await p.getByLabel('پروفایل', { exact: true }).click(); await p.getByRole('menuitem', { name: 'خروج' }).click(); await p.waitForTimeout(150)
  await login(p, 'n.rahimi')
  await p.locator('aside nav').getByRole('button', { name: 'مدیریت' }).click(); await p.waitForTimeout(250)
  await p.getByRole('tab', { name: 'AuditLog' }).click(); await p.waitForTimeout(150)
  await p.locator('#audit-kind').click(); await p.getByRole('option', { name: 'Work Log' }).click(); await p.waitForTimeout(150)
  await p.locator('li:has-text("آزمون E2E") button').first().click(); await p.waitForTimeout(500)
  ok((await p.locator('#task-drawer-scroll h2').first().innerText()).trim() === taskTitle, 'همان تسک از AuditLog باز شد')
  ok(await p.locator('#worklog >> text=سوابق همه‌ی افراد').count() && await p.locator('#worklog >> text=به تفکیک افراد').count(), 'کنترل پروژه سوابق همه و تفکیک افراد را می‌بیند')
  const r2 = p.locator('#worklog li:has-text("آزمون E2E")')
  await r2.getByLabel('حذف رکورد').click(); await p.waitForTimeout(100)
  await p.locator('#worklog').getByRole('button', { name: 'حذف', exact: true }).click(); await p.waitForTimeout(200)
  ok((await p.locator('[data-sonner-toast]').allInnerTexts()).join(' ').includes('دلیل'), 'حذف رکورد دیگران بدون دلیل پذیرفته نشد')
  await p.locator('#worklog input[aria-label="دلیل حذف"]').fill('ثبت روی تسک اشتباه'); await p.locator('#worklog').getByRole('button', { name: 'حذف', exact: true }).click(); await p.waitForTimeout(250)
  ok(!(await p.locator('#worklog li:has-text("آزمون E2E")').count()), 'رکورد از سوابق فعال رفت')
  await p.locator('#worklog').getByRole('button', { name: /رکورد حذف‌شده/ }).click(); await p.waitForTimeout(100)
  ok(await p.locator('#worklog >> text=ثبت روی تسک اشتباه').count(), 'رکورد حذف‌شده با دلیل نگه داشته شد')
  await p.locator('#worklog').scrollIntoViewIfNeeded()
  await p.screenshot({ path: SHOTS + 'wl-control.png' })
  await p.keyboard.press('Escape'); await p.close()

  console.log('کسی که در تسک نقشی ندارد')
  p = await open('dark')
  await login(p, 'sh.hosseini')
  await p.locator('aside nav').getByRole('button', { name: 'پروژه‌ها' }).click(); await p.waitForTimeout(200)
  await p.locator('text=برج مسکونی بابلسر').first().click(); await p.waitForTimeout(300)
  await p.getByRole('tab', { name: 'رندر' }).click(); await p.waitForTimeout(200)
  await p.locator('[role=tabpanel] .glass-item.is-interactive').first().click(); await p.waitForTimeout(500)
  ok(!(await p.locator('#wl-h').count()) && await p.locator('#worklog >> text=ثبت زمان روی این تسک برای مسئول').count(), 'فرم ثبت زمان برای او نیست')
  ok(await p.locator('#worklog >> text=هنوز زمانی ثبت نکرده‌اید.').count(), 'سوابق دیگران را نمی‌بیند')
  await p.locator('#worklog').scrollIntoViewIfNeeded()
  await p.screenshot({ path: SHOTS + 'wl-dark-other.png' })
  await p.close()

  console.log('موبایل')
  p = await open('light', { width: 390, height: 844 })
  await login(p, 's.rezaei')
  await p.locator('[role=tabpanel] tbody tr').first().click(); await p.waitForTimeout(500)
  await p.locator('#worklog').scrollIntoViewIfNeeded()
  const over = await p.evaluate(() => { const el = document.getElementById('task-drawer-scroll'); return el.scrollWidth - el.clientWidth })
  ok(over <= 0, `بدون اسکرول افقی در صفحه‌ی تسک موبایل (${over})`)
  await p.screenshot({ path: SHOTS + 'wl-m.png' })
  await p.close()

  ok(errs.length === 0, 'بدون خطای صفحه')
  if (errs.length) console.log(errs.join('\n'))
  console.log(`\n${pass} passed, ${fail} failed`)
  await b.close(); process.exit(fail ? 1 : 0)
})()
