// Core flows not covered by the feature suites (Playwright, Chromium): sign-up → approval → sign-in, wrong password,
// chat with @mention → notification → click-through, Persian/Latin digits, theme, profile and password change.
const { chromium } = require('playwright')
const path = require('path')
const PAGE = process.env.PAGE || 'file://' + path.resolve(__dirname, '../dist/preview.html')
let pass = 0, fail = 0
const ok = (c, name) => { if (c) { pass++; console.log('  ✓', name) } else { fail++; console.log('  ✗', name) } }

;(async () => {
  const b = await chromium.launch()
  const errs = []
  const p = await b.newPage({ viewport: { width: 1366, height: 900 } })
  p.on('pageerror', (e) => errs.push(e.message))
  const toastHas = async (text) => (await p.locator('[data-sonner-toast]', { hasText: text }).count()) > 0
  const logout = async () => { if (await p.getByLabel('پروفایل', { exact: true }).count()) { await p.getByLabel('پروفایل', { exact: true }).click(); await p.getByRole('menuitem', { name: 'خروج' }).click(); await p.waitForTimeout(200) } }
  const login = async (u, pw = 'pargar1405') => { await logout(); await p.fill('#li-user', u); await p.fill('#li-pass', pw); await p.click('button[type=submit]'); await p.waitForTimeout(450) }
  const nav = (name) => p.locator('aside nav').getByRole('button', { name }).first().click().then(() => p.waitForTimeout(350))
  await p.goto(PAGE); await p.waitForTimeout(300)

  console.log('ورود و ثبت‌نام')
  await p.fill('#li-user', 'n.rahimi'); await p.fill('#li-pass', 'wrong-pass'); await p.click('button[type=submit]'); await p.waitForTimeout(250)
  ok(await p.locator('text=نام کاربری یا رمز عبور درست نیست').count() && await p.locator('#li-user').count(), 'رمز اشتباه: پیام خطا و ماندن در صفحه‌ی ورود')
  await p.getByRole('tab', { name: 'ایجاد حساب' }).click(); await p.waitForTimeout(150)
  await p.fill('#rg-name', 'سپیده احمدی'); await p.fill('#rg-user', 'n.rahimi'); await p.fill('#rg-pass', 'abc12345'); await p.fill('#rg-again', 'abc12345')
  await p.getByRole('button', { name: 'ارسال درخواست عضویت' }).click(); await p.waitForTimeout(200)
  ok(await p.locator('text=قبلاً گرفته شده است').count(), 'نام کاربری تکراری پذیرفته نمی‌شود')
  await p.fill('#rg-user', 's.ahmadi'); await p.fill('#rg-again', 'abc1234')
  await p.getByRole('button', { name: 'ارسال درخواست عضویت' }).click(); await p.waitForTimeout(200)
  ok(await p.locator('text=تکرار رمز عبور با خودش یکی نیست').count(), 'تکرار رمز نادرست پذیرفته نمی‌شود')
  await p.fill('#rg-again', 'abc12345')
  await p.getByRole('button', { name: 'ارسال درخواست عضویت' }).click(); await p.waitForTimeout(300)
  await p.getByRole('button', { name: 'بازگشت به ورود' }).click(); await p.waitForTimeout(150)
  await p.fill('#li-pass', 'abc12345'); await p.click('button[type=submit]'); await p.waitForTimeout(300)
  ok(await p.locator('text=هنوز تأیید نشده است').count(), 'حساب تأییدنشده وارد نمی‌شود')
  await login('n.rahimi')
  ok(await p.locator('aside nav').getByRole('button', { name: /مدیریت/ }).locator('span.num').count(), 'کنترل پروژه نشان درخواست عضویت را در منو می‌بیند')
  await nav('مدیریت')
  const row = p.locator('li, tr, div', { hasText: '@s.ahmadi' }).filter({ has: p.getByRole('button', { name: 'تأیید' }) }).last()
  const uid = await row.locator('[id^="rq-team-"]').first().getAttribute('id')
  await p.locator(`#${uid}`).click(); await p.getByRole('option', { name: 'ارائه' }).click(); await p.waitForTimeout(100)
  await row.getByRole('button', { name: 'تأیید' }).click(); await p.waitForTimeout(300)
  ok(await toastHas('حساب s.ahmadi تأیید شد'), 'تأیید عضویت با تیم و نقش')
  await login('s.ahmadi', 'abc12345')
  ok(await p.locator('text=سپیده احمدی').count() && !(await p.locator('#li-user').count()), 'کاربر تأییدشده وارد می‌شود')

  console.log('چت، منشن و اعلان')
  await nav('چت عمومی')
  await p.locator('[id^="chat-input-"]').fill('سلام @s.rezaei، جلسه‌ی هماهنگی فردا ساعت ۱۰ است.')
  await p.getByRole('button', { name: 'ارسال' }).last().click(); await p.waitForTimeout(250)
  ok(await p.locator('main', { hasText: 'جلسه‌ی هماهنگی فردا ساعت ۱۰ است' }).count(), 'پیام در چت عمومی ثبت شد')
  await login('s.rezaei')
  await nav('اعلان‌ها')
  const notif = p.locator('main button', { hasText: 'سپیده احمدی شما را در چت عمومی تگ کرد' }).first()
  ok(await notif.count(), 'کاربر منشن‌شده اعلان گرفت')
  await notif.click(); await p.waitForTimeout(350)
  ok(await p.locator('main', { hasText: 'جلسه‌ی هماهنگی فردا' }).count(), 'کلیک روی اعلان به همان چت می‌رود')
  await nav('اعلان‌ها')
  const taskNotif = p.locator('main button', { hasText: '«' }).filter({ hasNotText: 'چت' }).first()
  if (await taskNotif.count()) {
    await taskNotif.click(); await p.waitForTimeout(400)
    ok(await p.locator('#task-drawer-scroll').count() || (await p.locator('main h1').count()), 'کلیک روی اعلان تسک، تسک یا صفحه‌ی مقصد را باز می‌کند')
    await p.keyboard.press('Escape'); await p.waitForTimeout(200)
  }

  console.log('ارقام، تم و پروفایل')
  const clock = async () => (await p.locator('header').first().innerText())
  ok(/[۰-۹]/.test(await clock()), 'ارقام فارسی به‌صورت پیش‌فرض')
  await p.locator('#fa-digits').click(); await p.waitForTimeout(150)
  ok(/[0-9]/.test(await clock()) && !/[۰-۹]/.test((await clock()).replace(/[^0-9۰-۹]/g, '').slice(0, 4)), 'خاموش کردن ارقام فارسی: ارقام لاتین')
  await p.locator('#fa-digits').click(); await p.waitForTimeout(150)
  await p.locator('header').getByRole('button', { name: /^تم:/ }).first().click(); await p.waitForTimeout(150)
  await p.getByRole('menuitem', { name: 'تاریک' }).click(); await p.waitForTimeout(200)
  ok(await p.evaluate(() => document.documentElement.getAttribute('data-theme')) === 'dark', 'تم تیره اعمال شد')
  await p.locator('header').getByRole('button', { name: /^تم:/ }).first().click(); await p.waitForTimeout(150)
  await p.getByRole('menuitem', { name: 'روشن' }).click(); await p.waitForTimeout(200)
  ok(await p.evaluate(() => document.documentElement.getAttribute('data-theme')) === 'light', 'تم روشن اعمال شد')
  await p.getByLabel('پروفایل', { exact: true }).click(); await p.getByRole('menuitem', { name: /پروفایل/ }).first().click(); await p.waitForTimeout(300)
  await p.fill('#pf-phone', 'داخلی ۲۴۰')
  await p.fill('#pf-pw-current', 'wrong'); await p.fill('#pf-pw-next', 'newpass99'); await p.fill('#pf-pw-again', 'newpass99')
  await p.getByRole('dialog').getByRole('button', { name: 'ذخیره' }).click(); await p.waitForTimeout(200)
  ok(await toastHas('رمز فعلی درست نیست') && await p.getByRole('dialog').count(), 'تغییر رمز با رمز فعلی اشتباه انجام نمی‌شود')
  await p.fill('#pf-pw-current', 'pargar1405')
  await p.getByRole('dialog').getByRole('button', { name: 'ذخیره' }).click(); await p.waitForTimeout(250)
  ok(await toastHas('پروفایل شما ذخیره شد'), 'پروفایل و رمز تازه ذخیره شد')
  await login('s.rezaei', 'pargar1405')
  ok(await p.locator('#li-user').count(), 'رمز قبلی دیگر کار نمی‌کند')
  await login('s.rezaei', 'newpass99')
  ok(!(await p.locator('#li-user').count()), 'ورود با رمز تازه')

  ok(errs.length === 0, `بدون خطای صفحه${errs.length ? `: ${errs.join(' | ')}` : ''}`)
  await b.close()
  console.log(`\n${pass} pass, ${fail} fail`)
  process.exit(fail ? 1 : 0)
})()
