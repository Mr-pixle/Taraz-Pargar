// Personal tasks end-to-end checks (Playwright, Chromium)
const { chromium } = require('playwright')
const path = require('path')
const SHOTS = process.env.SHOTS || require('path').resolve(__dirname, '.out/shots') + '/'
require('fs').mkdirSync(SHOTS, { recursive: true })
const PAGE = process.env.PAGE || 'file://' + path.resolve(__dirname, '../dist/preview.html')
let pass = 0, fail = 0
const ok = (c, name) => { if (c) { pass++; console.log('  ✓', name) } else { fail++; console.log('  ✗', name) } }

;(async () => {
  const b = await chromium.launch()
  const errs = []
  const open = async (scheme = 'light', vp = { width: 1366, height: 900 }) => {
    const p = await b.newPage({ viewport: vp, colorScheme: scheme })
    p.on('pageerror', (e) => errs.push(e.message))
    await p.goto(PAGE); await p.waitForTimeout(300)
    return p
  }
  const login = async (p, u) => {
    if (await p.getByLabel('پروفایل', { exact: true }).count()) { await p.getByLabel('پروفایل', { exact: true }).click(); await p.getByRole('menuitem', { name: 'خروج' }).click(); await p.waitForTimeout(150) }
    await p.fill('#li-user', u); await p.fill('#li-pass', 'pargar1405'); await p.click('button[type=submit]'); await p.waitForTimeout(400)
  }
  const nav = (p, name) => p.locator('aside nav').getByRole('button', { name }).first().click().then(() => p.waitForTimeout(350))
  const col = (p, name) => p.getByRole('list', { name: `ستون ${name}` })
  const card = (p, title) => p.locator('[data-ptask]', { hasText: title }).first()
  const dlg = (p) => p.getByRole('dialog')

  console.log('Kanban و Subtask')
  const p = await open()
  await login(p, 's.rezaei')
  const group = await p.locator('aside nav > div', { hasText: 'کار' }).first().innerText()
  ok(group.includes('کارهای شخصی'), '«کارهای شخصی» در گروه «کار» منو')
  await nav(p, 'کارهای شخصی')
  ok(await p.getByRole('list', { name: /^ستون / }).count() === 5, 'Kanban با پنج Status اختصاصی کاربر')
  // quick add in a column
  await col(p, 'ایده').getByRole('button', { name: 'افزودن' }).click()
  await p.getByLabel('کار تازه در ایده').fill('مطالعه‌ی معماری پارامتریک')
  await p.keyboard.press('Enter'); await p.waitForTimeout(250); await p.keyboard.press('Escape')
  ok(await col(p, 'ایده').locator('[data-ptask]', { hasText: 'مطالعه‌ی معماری پارامتریک' }).count() === 1, 'ساخت سریع کار در همان ستون')
  // drag & drop between columns
  await card(p, 'مطالعه‌ی معماری پارامتریک').dragTo(col(p, 'در حال انجام')); await p.waitForTimeout(300)
  ok(await col(p, 'در حال انجام').locator('[data-ptask]', { hasText: 'مطالعه‌ی معماری پارامتریک' }).count() === 1, 'Drag & Drop کارت، Status را عوض کرد')
  // subtasks
  await card(p, 'مطالعه‌ی معماری پارامتریک').click(); await p.waitForTimeout(300)
  for (const s of ['Grasshopper مقدماتی', 'پروژه‌ی تمرینی']) { await dlg(p).getByLabel('Subtask تازه').fill(s); await p.keyboard.press('Enter'); await p.waitForTimeout(150) }
  const subs = dlg(p).locator('section[aria-label="Subtaskها"] li')
  ok((await subs.nth(0).innerText()).includes('Grasshopper') && (await subs.nth(1).innerText()).includes('پروژه‌ی تمرینی'), 'دو Subtask ساخته شد')
  await dlg(p).getByRole('button', { name: 'بالا بردن «پروژه‌ی تمرینی»' }).click(); await p.waitForTimeout(150)
  ok((await subs.nth(0).innerText()).includes('پروژه‌ی تمرینی'), 'جابه‌جایی Subtask')
  await dlg(p).getByRole('checkbox', { name: 'تکمیل «پروژه‌ی تمرینی»' }).click(); await p.waitForTimeout(150)
  ok((await dlg(p).locator('section[aria-label="Subtaskها"]').innerText()).includes('۱ از ۲ تکمیل'), 'وضعیت تکمیل Subtask و پیشرفت')
  await dlg(p).getByRole('button', { name: 'Grasshopper مقدماتی', exact: true }).click(); await p.waitForTimeout(250)
  ok(await dlg(p).getByRole('navigation', { name: 'مسیر' }).locator('text=مطالعه‌ی معماری پارامتریک').count() === 1, 'Subtask با مسیر Task اصلی باز شد')
  await dlg(p).getByLabel('Subtask تازه').fill('نصب افزونه‌ها'); await p.keyboard.press('Enter'); await p.waitForTimeout(150)
  ok(await dlg(p).locator('section[aria-label="Subtaskها"] li', { hasText: 'نصب افزونه‌ها' }).count() === 1, 'Subtask سطح سوم')
  await p.screenshot({ path: SHOTS + 'pt-e2e-dialog.png' })
  await p.keyboard.press('Escape'); await p.waitForTimeout(200)
  ok((await card(p, 'مطالعه‌ی معماری پارامتریک').innerText()).includes('۱/۲'), 'کارت پیشرفت Subtaskها را نشان می‌دهد')
  await p.getByRole('checkbox', { name: /Subtaskها هم کارت شوند/ }).click().catch(async () => { await p.locator('label', { hasText: 'Subtaskها هم کارت شوند' }).click() })
  await p.waitForTimeout(200)
  ok(await card(p, 'Grasshopper مقدماتی').count() === 1 && (await card(p, 'Grasshopper مقدماتی').innerText()).includes('مطالعه‌ی معماری پارامتریک'), 'نمایش Subtaskها به‌صورت کارت با مسیر')

  console.log('Statusهای اختصاصی')
  await p.getByRole('button', { name: 'Statusها' }).click(); await p.waitForTimeout(250)
  await dlg(p).getByRole('button', { name: 'Status تازه' }).click()
  await dlg(p).getByLabel('نام Status').last().fill('متوقف')
  await dlg(p).getByRole('button', { name: 'رنگ «متوقف»' }).click()
  await dlg(p).getByRole('radio', { name: '#d6453f' }).click()
  await dlg(p).getByRole('button', { name: 'حذف «منتظر دیگران»' }).click()
  await dlg(p).getByRole('button', { name: 'ذخیره' }).click(); await p.waitForTimeout(250)
  ok(await dlg(p).count() === 1 && await p.locator('[data-sonner-toast]', { hasText: 'Status تازه انتخاب کنید' }).count() >= 1, 'حذف Status پر بدون انتخاب جایگزین رد شد')
  await dlg(p).getByRole('combobox', { name: 'Status تازه برای کارهای «منتظر دیگران»' }).click()
  await p.getByRole('option', { name: 'متوقف' }).click()
  await dlg(p).locator('input[name="ps-default"]').last().check()
  await dlg(p).getByRole('button', { name: 'ذخیره' }).click(); await p.waitForTimeout(300)
  ok(await col(p, 'متوقف').count() === 1 && await col(p, 'منتظر دیگران').count() === 0, 'Status تازه اضافه شد و Status حذف‌شده رفت')
  ok(await col(p, 'متوقف').locator('[data-ptask]', { hasText: 'تمدید گواهینامه' }).count() === 1, 'کارهای Status حذف‌شده منتقل شد')
  ok((await col(p, 'متوقف').innerText()).includes('پیش‌فرض'), 'Status پیش‌فرض تازه')
  await p.getByRole('button', { name: 'کار تازه' }).click(); await p.waitForTimeout(200)
  await p.fill('#pn-title', 'کار با پیش‌فرض تازه'); await dlg(p).getByRole('button', { name: 'ساخت' }).click(); await p.waitForTimeout(250)
  const where = await p.locator('[data-ptask]', { hasText: 'کار با پیش‌فرض تازه' }).evaluateAll((els) => els.map((e) => e.closest('[role=list]')?.getAttribute('aria-label')))
  ok(where.length === 1 && where[0] === 'ستون متوقف', `کار تازه در Status پیش‌فرض ساخته شد (${where.join('، ')})`)
  await p.screenshot({ path: SHOTS + 'pt-e2e-kanban.png', fullPage: true })

  console.log('Timeline')
  await p.getByRole('tab', { name: 'Timeline' }).click(); await p.waitForTimeout(500)
  const grid = p.getByRole('grid', { name: 'Timeline کارهای شخصی' })
  ok(await grid.count() === 1, 'نمای Timeline')
  const bar = grid.locator('[data-pbar]').filter({ hasText: 'مطالعه‌ی فصل‌های ۴ تا ۶' }).first()
  const before = await bar.getAttribute('aria-label')
  const bb = await bar.boundingBox()
  await p.mouse.move(bb.x + bb.width / 2, bb.y + bb.height / 2); await p.mouse.down()
  await p.mouse.move(bb.x + bb.width / 2 - 35, bb.y + bb.height / 2, { steps: 4 }); await p.mouse.move(bb.x + bb.width / 2 - 60, bb.y + bb.height / 2, { steps: 4 }); await p.mouse.up(); await p.waitForTimeout(300)
  const after = await grid.locator('[data-pbar]').filter({ hasText: 'مطالعه‌ی فصل‌های ۴ تا ۶' }).first().getAttribute('aria-label')
  ok(before !== after, `کشیدن نوار تاریخ‌ها را جابه‌جا کرد (${after})`)
  const handle = grid.locator('[data-pbar]').filter({ hasText: 'مطالعه‌ی فصل‌های ۴ تا ۶' }).first()
  const hb = await handle.boundingBox()
  await p.mouse.move(hb.x + 3, hb.y + hb.height / 2); await p.mouse.down(); await p.mouse.move(hb.x - 60, hb.y + hb.height / 2, { steps: 5 }); await p.mouse.up(); await p.waitForTimeout(300)
  const after2 = await grid.locator('[data-pbar]').filter({ hasText: 'مطالعه‌ی فصل‌های ۴ تا ۶' }).first().getAttribute('aria-label')
  ok(after2 !== after && after2.split('تا')[0] === after.split('تا')[0], 'کشیدن لبه فقط موعد را تغییر داد')
  const row = grid.getByRole('row').filter({ hasText: 'کتاب «زبان الگو»' })
  ok(await row.locator('text=بدون تاریخ').count() === 1, 'کار بدون تاریخ علامت دارد')
  await row.evaluate((el) => el.scrollIntoView({ block: 'center' })); await p.waitForTimeout(150)
  const tl = row.locator('div.cursor-copy')
  const tb = await tl.boundingBox(); const vb = await grid.boundingBox()
  await p.mouse.click(vb.x + vb.width * 0.3, tb.y + tb.height / 2); await p.waitForTimeout(250)
  ok(await row.locator('text=بدون تاریخ').count() === 0 && await row.locator('[data-pbar]').count() === 1, 'کلیک روی روز، کار بدون تاریخ را زمان‌بندی کرد')
  ok(await grid.locator('[title="بازه‌ی Subtaskها"]').count() >= 1, 'بازه‌ی Subtaskها زیر Task اصلی')
  await p.screenshot({ path: SHOTS + 'pt-e2e-timeline.png', fullPage: true })

  console.log('تفکیک و جدایی از داده‌ی سازمانی')
  await nav(p, 'خانه')
  ok(!(await p.locator('main', { hasText: 'LEED' }).count()) && !(await p.locator('main', { hasText: 'معماری پارامتریک' }).count()), 'کارهای شخصی در خانه و داشبورد نیست')
  await p.locator('main').getByRole('tab', { name: 'تقویم' }).first().click().catch(() => {}); await p.waitForTimeout(250)
  ok(!(await p.locator('main', { hasText: 'معماری پارامتریک' }).count()), 'کارهای شخصی در تقویم کاری نیست')
  await login(p, 'ceo')
  await nav(p, 'کارهای شخصی')
  ok(await p.locator('main', { hasText: 'هنوز کار شخصی‌ای ندارید' }).count() === 1 && !(await p.locator('main', { hasText: 'LEED' }).count()), 'مدیرعامل فهرست شخصی خودش را دارد و کارهای دیگران را نمی‌بیند')
  ok((await p.getByRole('list', { name: /^ستون / }).count()) === 0, 'مدیرعامل Statusهای خودش را دارد (پیش‌فرض)')
  await login(p, 'n.rahimi')
  await nav(p, 'کارهای شخصی')
  ok(await card(p, 'Primavera').count() === 1 && !(await p.locator('main', { hasText: 'LEED' }).count()) && await p.getByRole('list', { name: /^ستون / }).count() === 3, 'کنترل پروژه فقط فهرست و Statusهای خودش را می‌بیند')
  await nav(p, 'مدیریت')
  const auditTab = p.getByRole('tab', { name: 'AuditLog' })
  if (await auditTab.count()) { await auditTab.click(); await p.waitForTimeout(250) }
  ok(!(await p.locator('main', { hasText: 'معماری پارامتریک' }).count()) && !(await p.locator('main', { hasText: 'LEED' }).count()), 'هیچ اثری از کارهای شخصی در AuditLog نیست')
  await nav(p, 'Workload')
  ok(!(await p.locator('main', { hasText: 'معماری پارامتریک' }).count()), 'کارهای شخصی در Workload نیست')

  console.log('موبایل و تیره')
  const m = await open('dark', { width: 390, height: 844 })
  await login(m, 's.rezaei')
  await m.getByRole('button', { name: 'منو', exact: true }).click(); await m.waitForTimeout(800)
  await m.getByRole('dialog').getByRole('button', { name: 'کارهای شخصی' }).click(); await m.waitForTimeout(500)
  ok(await m.evaluate(() => document.documentElement.scrollWidth - window.innerWidth) <= 1, 'Kanban در موبایل اسکرول افقی صفحه ندارد')
  await m.screenshot({ path: SHOTS + 'pt-mobile.png' })
  await m.getByRole('tab', { name: 'Timeline' }).click(); await m.waitForTimeout(400)
  ok(await m.evaluate(() => document.documentElement.scrollWidth - window.innerWidth) <= 1, 'Timeline در موبایل اسکرول افقی صفحه ندارد')
  await m.screenshot({ path: SHOTS + 'pt-mobile-timeline.png' })
  await m.close()

  ok(errs.length === 0, 'بدون خطای صفحه' + (errs.length ? ': ' + errs.join(' | ') : ''))
  await b.close()
  console.log(`\n${pass} pass, ${fail} fail`)
  process.exit(fail ? 1 : 0)
})()
